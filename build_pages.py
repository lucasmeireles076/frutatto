def pic(name, widths, sizes, alt, *, lazy=True, extra="", ratio=(757, 1437)):
    avif = ", ".join(f"img/{name}-{w}.avif {w}w" for w in widths)
    webp = ", ".join(f"img/{name}-{w}.webp {w}w" for w in widths)
    load = 'loading="lazy" ' if lazy else 'fetchpriority="high" '
    return (f'<picture><source type="image/avif" srcset="{avif}" sizes="{sizes}">'
            f'<img src="img/{name}-{widths[1]}.webp" srcset="{webp}" sizes="{sizes}" '
            f'width="{ratio[0]}" height="{ratio[1]}" alt="{alt}" {load}decoding="async"{extra}></picture>')


