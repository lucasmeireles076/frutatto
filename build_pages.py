def title_html(lines):
    out = []
    for line in lines:
        words = " ".join(
            f'<span class="word accent">{w[1:]}</span>' if w.startswith("*") else f'<span class="word">{w}</span>'
            for w in line)
        out.append(f'<span class="line">{words}</span>')
    return "\n            ".join(out)


